/**
 * Integration tests for the LedgerBase transaction engine.
 *
 * These tests use the real:
 * - TransactionService
 * - MyBatis mappers
 * - PostgreSQL database
 *
 * The "test" profile selects ledgerbase_test.
 *
 * Each test runs inside a transaction that Spring
 * automatically rolls back after the test finishes.
 */
@SpringBootTest
@ActiveProfiles("test")
@Transactional
class TransactionIntegrationTest {

    // Service containing our transaction creation logic.
    @Autowired
    private TransactionService transactionService;

    // Mapper used to retrieve saved ledger entries.
    @Autowired
    private LedgerEntryMapper entryMapper;

    // Executes SQL for test setup and verification.
    @Autowired
    private JdbcTemplate jdbcTemplate;

    /**
     * Provides Spring's real web application context.
     *
     * MockMvc uses this context to simulate HTTP requests
     * without starting a separate server.
     */
    @Autowired
    private WebApplicationContext context;

    // IDs generated by PostgreSQL for each test.
    private Long testUserId;
    private Long testBusinessId;
    private Long cashAccountId;
    private Long revenueAccountId;

    /**
     * Create a user, business and two accounts
     * before every test.
     *
     * All inserted records belong to the test
     * transaction and will be rolled back afterward.
     */
    @BeforeEach
    void setUpTestData() {

        // Generate a unique email for this test.
        String email = "transaction-test-"
            + UUID.randomUUID()
            + "@ledgerbase.local";

        // Create a temporary test user.
        testUserId = jdbcTemplate.queryForObject(
            """
            INSERT INTO users (
                email,
                password_hash,
                full_name
            )
            VALUES (?, ?, ?)
            RETURNING id
            """,
            Long.class,
            email,
            "TEST_ONLY_NOT_A_REAL_PASSWORD_HASH",
            "Transaction Test User"
        );

        // Create a business owned by the test user.
        testBusinessId = jdbcTemplate.queryForObject(
            """
            INSERT INTO businesses (
                owner_id,
                name,
                currency
            )
            VALUES (?, ?, ?)
            RETURNING id
            """,
            Long.class,
            testUserId,
            "Transaction Test Business",
            "USD"
        );

        // Create an asset account for incoming cash.
        cashAccountId = jdbcTemplate.queryForObject(
            """
            INSERT INTO accounts (
                business_id,
                code,
                name,
                account_type
            )
            VALUES (?, ?, ?, ?)
            RETURNING id
            """,
            Long.class,
            testBusinessId,
            "1000",
            "Cash",
            "ASSET"
        );

        // Create a revenue account for consulting income.
        revenueAccountId = jdbcTemplate.queryForObject(
            """
            INSERT INTO accounts (
                business_id,
                code,
                name,
                account_type
            )
            VALUES (?, ?, ?, ?)
            RETURNING id
            """,
            Long.class,
            testBusinessId,
            "4000",
            "Consulting Revenue",
            "REVENUE"
        );
    }

    /**
     * Build a transaction request using the
     * actual test user and account IDs.
     *
     * The amounts are supplied as strings and
     * converted to BigDecimal to preserve precision.
     */
    private CreateTransactionRequest createRequest(
            String debitAmount,
            String creditAmount) {

        return new CreateTransactionRequest(
            testUserId,
            "Consulting payment",
            LocalDate.of(2026, 10, 11),
            List.of(
                new CreateLedgerEntryRequest(
                    cashAccountId,
                    new BigDecimal(debitAmount),
                    new BigDecimal("0.00")
                ),
                new CreateLedgerEntryRequest(
                    revenueAccountId,
                    new BigDecimal("0.00"),
                    new BigDecimal(creditAmount)
                )
            )
        );
    }

    /**
     * Test 1:
     *
     * A balanced transaction should create:
     *
     * - One DRAFT transaction
     * - One debit entry
     * - One credit entry
     *
     * Both entries must reference the same
     * newly created transaction.
     */
    @Test
    void createsBalancedDraftTransaction() {

        // Create a balanced transaction:
        // Debit Cash 500, Credit Revenue 500.
        CreateTransactionRequest request =
            createRequest("500.00", "500.00");

        LedgerTransaction saved =
            transactionService.createDraftTransaction(
                testBusinessId,
                request
            );

        // PostgreSQL must generate a transaction ID.
        assertNotNull(saved.getId());

        // Newly created transactions must be drafts.
        assertEquals("DRAFT", saved.getStatus());

        // Verify business and creator information.
        assertEquals(testBusinessId, saved.getBusinessId());
        assertEquals(testUserId, saved.getCreatedBy());

        // Check that the transaction header exists
        // in the real database.
        Integer transactionCount =
            jdbcTemplate.queryForObject(
                """
                SELECT COUNT(*)
                FROM transactions
                WHERE id = ?
                  AND business_id = ?
                  AND status = 'DRAFT'
                """,
                Integer.class,
                saved.getId(),
                testBusinessId
            );

        assertEquals(1, transactionCount);

        // Retrieve the entries using our real MyBatis mapper.
        List<LedgerEntry> entries =
            entryMapper.findByTransactionId(
                testBusinessId,
                saved.getId()
            );

        // There should be exactly two ledger entries.
        assertEquals(2, entries.size());

        LedgerEntry debitEntry = entries.get(0);
        LedgerEntry creditEntry = entries.get(1);

        // Verify the debit affects the Cash account.
        assertEquals(
            cashAccountId,
            debitEntry.getAccountId()
        );

        assertEquals(
            0,
            new BigDecimal("500.00").compareTo(
                debitEntry.getDebit()
            )
        );

        assertEquals(
            0,
            BigDecimal.ZERO.compareTo(
                debitEntry.getCredit()
            )
        );

        // Verify the credit affects Consulting Revenue.
        assertEquals(
            revenueAccountId,
            creditEntry.getAccountId()
        );

        assertEquals(
            0,
            new BigDecimal("500.00").compareTo(
                creditEntry.getCredit()
            )
        );

        assertEquals(
            0,
            BigDecimal.ZERO.compareTo(
                creditEntry.getDebit()
            )
        );

        // Both entries must belong to the same transaction.
        assertEquals(
            saved.getId(),
            debitEntry.getTransactionId()
        );

        assertEquals(
            saved.getId(),
            creditEntry.getTransactionId()
        );
    }

    /**
     * Test 2:
     *
     * An unbalanced transaction must be rejected
     * before inserting any financial records.
     *
     * Debit Cash:       500.00
     * Credit Revenue:   400.00
     *
     * These totals do not match.
     */
    @Test
    void rejectsUnbalancedTransactionWithoutSaving() {

        CreateTransactionRequest request =
            createRequest("500.00", "400.00");

        // The service should reject the request.
        IllegalArgumentException exception =
            assertThrows(
                IllegalArgumentException.class,
                () -> transactionService.createDraftTransaction(
                    testBusinessId,
                    request
                )
            );

        assertEquals(
            "Total debits must equal total credits",
            exception.getMessage()
        );

        // Verify that no transaction header was inserted.
        Integer transactionCount =
            jdbcTemplate.queryForObject(
                """
                SELECT COUNT(*)
                FROM transactions
                WHERE business_id = ?
                """,
                Integer.class,
                testBusinessId
            );

        assertEquals(0, transactionCount);

        // Verify that no ledger entries were inserted.
        Integer entryCount =
            jdbcTemplate.queryForObject(
                """
                SELECT COUNT(*)
                FROM ledger_entries
                WHERE business_id = ?
                """,
                Integer.class,
                testBusinessId
            );

        assertEquals(0, entryCount);
    }

    /**
     * Test 3:
     *
     * Verify that an HTTP POST request creates a DRAFT
     * financial transaction and saves its ledger entries.
     *
     * This tests the complete flow:
     *
     * HTTP POST
     *   -> TransactionController
     *   -> TransactionService
     *   -> MyBatis mappers
     *   -> PostgreSQL
     *
     * The test transaction is automatically rolled back
     * afterward because this test class is @Transactional.
     */
    @Test
    void createsDraftTransactionThroughHttp() throws Exception {

        // Build MockMvc using the real Spring web context.
        MockMvc mvc = MockMvcBuilders
            .webAppContextSetup(context)
            .build();

        // Construct the API URL using our temporary business ID.
        String url = "/api/v1/businesses/"
            + testBusinessId
            + "/transactions";

        /*
        * Build the JSON request using database-generated IDs.
        *
        * The first ledger entry debits Cash $500.
        * The second credits Consulting Revenue $500.
        *
        * Both entries are balanced.
        */
        String requestBody = """
            {
            "createdBy": %d,
            "description": "Consulting payment",
            "transactionDate": "2026-10-11",
            "entries": [
                {
                "accountId": %d,
                "debit": 500.00,
                "credit": 0.00
                },
                {
                "accountId": %d,
                "debit": 0.00,
                "credit": 500.00
                }
            ]
            }
            """.formatted(
                testUserId,
                cashAccountId,
                revenueAccountId
            );

        /*
        * Send the POST request.
        *
        * Verify:
        * - HTTP 201 Created
        * - DRAFT status
        * - Correct business ID
        * - Correct description
        */
        mvc.perform(
                post(url)
                    .contentType(MediaType.APPLICATION_JSON)
                    .content(requestBody)
            )
            .andExpect(status().isCreated())
            .andExpect(jsonPath("$.id").isNumber())
            .andExpect(jsonPath("$.status").value("DRAFT"))
            .andExpect(
                jsonPath("$.businessId").value(testBusinessId)
            )
            .andExpect(
                jsonPath("$.description")
                    .value("Consulting payment")
            );

        /*
        * Independently verify that exactly one DRAFT
        * transaction was saved in PostgreSQL.
        */
        Integer transactionCount =
            jdbcTemplate.queryForObject(
                """
                SELECT COUNT(*)
                FROM transactions
                WHERE business_id = ?
                AND status = 'DRAFT'
                """,
                Integer.class,
                testBusinessId
            );

        assertEquals(1, transactionCount);

        /*
        * Verify that the transaction has exactly
        * two saved ledger entries.
        */
        Integer entryCount =
            jdbcTemplate.queryForObject(
                """
                SELECT COUNT(*)
                FROM ledger_entries
                WHERE business_id = ?
                """,
                Integer.class,
                testBusinessId
            );

        assertEquals(2, entryCount);

        /*
        * Verify that total debits and total credits
        * are both exactly $500.00.
        *
        * BigDecimal.compareTo() compares numerical
        * values without requiring identical scales.
        */
        BigDecimal totalDebit = jdbcTemplate.queryForObject(
            """
            SELECT SUM(debit)
            FROM ledger_entries
            WHERE business_id = ?
            """,
            BigDecimal.class,
            testBusinessId
        );

        BigDecimal totalCredit = jdbcTemplate.queryForObject(
            """
            SELECT SUM(credit)
            FROM ledger_entries
            WHERE business_id = ?
            """,
            BigDecimal.class,
            testBusinessId
        );

        assertNotNull(totalDebit);
        assertNotNull(totalCredit);

        assertEquals(
            0,
            new BigDecimal("500.00").compareTo(totalDebit)
        );

        assertEquals(
            0,
            new BigDecimal("500.00").compareTo(totalCredit)
        );
    }

    /**
     * Verify that the GET endpoint retrieves transactions
     * belonging to our test business.
     *
     * First create a transaction using the service,
     * then retrieve it through the HTTP API.
     *
     * This exercises the real controller, service,
     * MyBatis mapper and PostgreSQL database.
     */
    @Test
    void listsTransactionsThroughHttp() throws Exception {

        // Create a balanced transaction using our test accounts.
        CreateTransactionRequest request =
            createRequest("500.00", "500.00");

        transactionService.createDraftTransaction(
            testBusinessId,
            request
        );

        // Simulate an HTTP request without starting Tomcat.
        MockMvc mvc = MockMvcBuilders
            .webAppContextSetup(context)
            .build();

        String url = "/api/v1/businesses/"
            + testBusinessId
            + "/transactions";

        // Expect one transaction with the correct information.
        mvc.perform(get(url))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$").isArray())
            .andExpect(jsonPath("$.length()").value(1))
            .andExpect(jsonPath("$[0].status").value("DRAFT"))
            .andExpect(
                jsonPath("$[0].description")
                    .value("Consulting payment")
            )
            .andExpect(
                jsonPath("$[0].businessId")
                    .value(testBusinessId)
            );
    }

    /**
     * Verify that GET /transactions/{transactionId}
     * returns the transaction header and ledger entries.
     *
     * We first create a real transaction in PostgreSQL,
     * then retrieve it through the HTTP API.
     */
    @Test
    void retrievesTransactionDetailsThroughHttp() throws Exception {

        // Create a balanced transaction using our test accounts.
        CreateTransactionRequest request =
            createRequest("500.00", "500.00");

        LedgerTransaction saved =
            transactionService.createDraftTransaction(
                testBusinessId,
                request
            );

        // Simulate an HTTP request through Spring MVC.
        MockMvc mvc = MockMvcBuilders
            .webAppContextSetup(context)
            .build();

        String url = "/api/v1/businesses/"
            + testBusinessId
            + "/transactions/"
            + saved.getId();

        /*
        * Verify the transaction header and both entries.
        *
        * The entries are ordered by ID because our
        * LedgerEntryMapper SQL uses ORDER BY id ASC.
        */
        mvc.perform(get(url))
            .andExpect(status().isOk())

            // Verify the transaction header.
            .andExpect(
                jsonPath("$.transaction.id").value(saved.getId())
            )
            .andExpect(
                jsonPath("$.transaction.status").value("DRAFT")
            )
            .andExpect(
                jsonPath("$.transaction.description")
                    .value("Consulting payment")
            )

            // Verify that two ledger entries are returned.
            .andExpect(
                jsonPath("$.entries.length()").value(2)
            )

            // First entry: Debit Cash $500.
            .andExpect(
                jsonPath("$.entries[0].accountId")
                    .value(cashAccountId)
            )
            .andExpect(
                jsonPath("$.entries[0].debit").value(500.0)
            )
            .andExpect(
                jsonPath("$.entries[0].credit").value(0.0)
            )

            // Second entry: Credit Revenue $500.
            .andExpect(
                jsonPath("$.entries[1].accountId")
                    .value(revenueAccountId)
            )
            .andExpect(
                jsonPath("$.entries[1].debit").value(0.0)
            )
            .andExpect(
                jsonPath("$.entries[1].credit").value(500.0)
            );
    }

    /**
     * Verify that transaction details are scoped
     * to the requested business.
     *
     * A transaction belonging to Business A
     * must not be returned through Business B's URL.
     *
     * Both businesses use our temporary test user.
     * This tests database query scoping, not
     * authentication or ownership authorization.
     */
    @Test
    void rejectsTransactionFromAnotherBusiness() throws Exception {

        // Create a valid transaction for Business A.
        LedgerTransaction saved =
            transactionService.createDraftTransaction(
                testBusinessId,
                createRequest("500.00", "500.00")
            );

        // Create Business B in the isolated test database.
        Long otherBusinessId = jdbcTemplate.queryForObject(
            """
            INSERT INTO businesses (
                owner_id,
                name,
                currency
            )
            VALUES (?, ?, ?)
            RETURNING id
            """,
            Long.class,
            testUserId,
            "Another Test Business",
            "USD"
        );

        MockMvc mvc = MockMvcBuilders
            .webAppContextSetup(context)
            .build();

        // Attempt to retrieve Business A's transaction
        // using Business B's URL.
        String url = "/api/v1/businesses/"
            + otherBusinessId
            + "/transactions/"
            + saved.getId();

        // The API must not return another business's data.
        mvc.perform(get(url))
            .andExpect(status().isNotFound())
            .andExpect(
                jsonPath("$.error").value(
                    "Transaction not found: " + saved.getId()
                )
            );
    }
}
