package com.ledgerbase.backend.dto;

import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;

// ============================================================
// LEDGERBASE — CREATE BUSINESS REQUEST DTO
// ============================================================

/**
 * Defines the JSON request body for creating a business.
 *
 * ENDPOINT:
 *
 * POST /api/v1/businesses
 *
 * EXAMPLE REQUEST:
 *
 * {
 *     "name": "ABC Consulting LLC",
 *     "currency": "USD",
 *     "fiscalYearStartMonth": 1
 * }
 *
 * RESPONSIBILITIES:
 *
 * 1. Accept business information from the frontend.
 * 2. Validate required fields using Jakarta Validation.
 * 3. Exclude database-managed and ownership fields.
 *
 * SECURITY:
 *
 * The client must not determine ownerId.
 *
 * Ownership must ultimately be determined using
 * the authenticated user's identity.
 *
 * Until authentication is implemented, the controller
 * will use our fixed local development owner.
 *
 * DATABASE-GENERATED FIELDS:
 *
 * id         — generated by PostgreSQL.
 * created_at — generated by PostgreSQL.
 *
 * Neither should be accepted from the client.
 *
 * VALIDATION:
 *
 * @Valid in BusinessController will trigger the
 * Jakarta Validation annotations below.
 *
 * Additional normalization and business rules
 * are implemented in BusinessService.
 */
public record CreateBusinessRequest(

    // ========================================================
    // BUSINESS NAME
    // ========================================================

    /**
     * Human-readable business name.
     *
     * Examples:
     *
     * ABC Consulting LLC
     * LedgerBase Demo Business
     *
     * Cannot be blank.
     *
     * PostgreSQL stores this as VARCHAR(200).
     */
    @NotBlank(message = "Business name is required")
    @Size(
        max = 200,
        message = "Business name must not exceed 200 characters"
    )
    String name,


    // ========================================================
    // BUSINESS CURRENCY
    // ========================================================

    /**
     * Three-letter currency code.
     *
     * Examples:
     *
     * USD
     * GBP
     * EUR
     *
     * Optional:
     *
     * If omitted (null), BusinessService uses USD.
     *
     * BusinessService also:
     *
     * - Trims surrounding whitespace.
     * - Converts lowercase letters to uppercase.
     * - Validates the three-letter format.
     *
     * We leave this field without a @Pattern annotation
     * so the service can normalize values first.
     */
    String currency,


    // ========================================================
    // FISCAL YEAR STARTING MONTH
    // ========================================================

    /**
     * Month in which the fiscal year begins.
     *
     * Valid range: 1 through 12.
     *
     * Examples:
     *
     * 1  = January
     * 4  = April
     * 7  = July
     * 10 = October
     *
     * Optional:
     *
     * If omitted (null), BusinessService uses January.
     *
     * @Min and @Max validate supplied values.
     *
     * Integer is used instead of int because an
     * optional JSON field must be able to be null.
     */
    @Min(
        value = 1,
        message = "Fiscal-year starting month must be at least 1"
    )
    @Max(
        value = 12,
        message = "Fiscal-year starting month must not exceed 12"
    )
    Integer fiscalYearStartMonth

) {
    // ========================================================
    // RECORD IMPLEMENTATION
    // ========================================================

    /**
     * Java automatically generates:
     *
     * - A constructor
     * - name()
     * - currency()
     * - fiscalYearStartMonth()
     * - equals()
     * - hashCode()
     * - toString()
     *
     * Records are a good fit for immutable API request DTOs.
     */
}
