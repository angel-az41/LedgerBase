package com.ledgerbase.backend.model;

import java.time.OffsetDateTime;

/**
 * Represents one financial account in a business's
 * Chart of Accounts.
 *
 * This model maps to the "accounts" PostgreSQL table.
 *
 * Examples:
 *
 * 1000 - Current Assets (non-postable grouping account)
 * 1010 - Cash (ASSET, CURRENT_ASSET)
 * 2000 - Accounts Payable (LIABILITY, CURRENT_LIABILITY)
 * 4000 - Sales Revenue (REVENUE, OPERATING_REVENUE)
 *
 * V7 introduces:
 *
 * 1. Reporting classifications for financial statements.
 * 2. Optional parent-child account relationships.
 * 3. Posting eligibility for journal entries.
 *
 * Account balances are calculated from ledger entries,
 * not stored directly in the accounts table.
 */
public class Account {

    // ========================================================
    // ACCOUNT IDENTITY
    // ========================================================

    // Unique database identifier (generated by PostgreSQL).
    private Long id;

    // ID of the business that owns this account.
    private Long businessId;


    // ========================================================
    // BASIC ACCOUNT INFORMATION
    // ========================================================

    // Human-readable account code, such as "1010".
    private String code;

    // Descriptive account name, such as "Cash".
    private String name;

    // ASSET, LIABILITY, EQUITY, REVENUE, or EXPENSE.
    private String accountType;


    // ========================================================
    // V7 — FINANCIAL REPORTING CLASSIFICATION
    // ========================================================

    /**
     * Determines the account's reporting category.
     *
     * Examples:
     *
     * CURRENT_ASSET
     * NON_CURRENT_ASSET
     * CURRENT_LIABILITY
     * NON_CURRENT_LIABILITY
     * CONTRIBUTED_CAPITAL
     * RETAINED_EARNINGS
     * OTHER_EQUITY
     * OPERATING_REVENUE
     * OTHER_INCOME
     * COST_OF_GOODS_SOLD
     * OPERATING_EXPENSE
     * OTHER_EXPENSE
     *
     * Corresponds to accounts.reporting_group.
     *
     * May be null for accounts that have not yet
     * received a reporting classification.
     */
    private String reportingGroup;


    // ========================================================
    // V7 — ACCOUNT HIERARCHY
    // ========================================================

    /**
     * ID of this account's optional parent.
     *
     * Example:
     *
     * 1000 - Current Assets
     *   1010 - Cash
     *   1020 - Accounts Receivable
     *
     * In this example:
     *
     * Cash.parentAccountId = Current Assets.id
     *
     * Corresponds to accounts.parent_account_id.
     *
     * Null means this account is at the top level.
     *
     * PostgreSQL ensures parent accounts belong to
     * the same business and cannot create cycles.
     */
    private Long parentAccountId;


    // ========================================================
    // ACCOUNT STATUS AND POSTING ELIGIBILITY
    // ========================================================

    /**
     * Whether the account is active for normal use.
     *
     * Corresponds to accounts.is_active.
     *
     * This is separate from posting eligibility.
     *
     * An inactive account can remain in historical
     * financial reports.
     */
    private Boolean active;

    /**
     * Whether the account may receive ledger entries.
     *
     * Corresponds to accounts.is_postable.
     *
     * TRUE:
     *   Normal posting account, such as Cash.
     *
     * FALSE:
     *   Organizational grouping account,
     *   such as Current Assets.
     *
     * Existing accounts default to TRUE in V7.
     *
     * PostgreSQL triggers enforce posting eligibility
     * even when operations bypass Spring Boot.
     */
    private Boolean postable;


    // ========================================================
    // AUDIT INFORMATION
    // ========================================================

    // When the account was created in PostgreSQL.
    private OffsetDateTime createdAt;


    // ========================================================
    // CONSTRUCTORS
    // ========================================================

    /**
     * Empty constructor allows MyBatis and other
     * frameworks to instantiate this model.
     */
    public Account() {
    }


    // ========================================================
    // GETTERS AND SETTERS — ACCOUNT IDENTITY
    // ========================================================

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Long getBusinessId() {
        return businessId;
    }

    public void setBusinessId(Long businessId) {
        this.businessId = businessId;
    }


    // ========================================================
    // GETTERS AND SETTERS — BASIC INFORMATION
    // ========================================================

    public String getCode() {
        return code;
    }

    public void setCode(String code) {
        this.code = code;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getAccountType() {
        return accountType;
    }

    public void setAccountType(String accountType) {
        this.accountType = accountType;
    }


    // ========================================================
    // GETTERS AND SETTERS — V7 REPORTING GROUP
    // ========================================================

    public String getReportingGroup() {
        return reportingGroup;
    }

    public void setReportingGroup(String reportingGroup) {
        this.reportingGroup = reportingGroup;
    }


    // ========================================================
    // GETTERS AND SETTERS — V7 ACCOUNT HIERARCHY
    // ========================================================

    public Long getParentAccountId() {
        return parentAccountId;
    }

    public void setParentAccountId(Long parentAccountId) {
        this.parentAccountId = parentAccountId;
    }


    // ========================================================
    // GETTERS AND SETTERS — ACCOUNT STATUS
    // ========================================================

    public Boolean getActive() {
        return active;
    }

    public void setActive(Boolean active) {
        this.active = active;
    }

    public Boolean getPostable() {
        return postable;
    }

    public void setPostable(Boolean postable) {
        this.postable = postable;
    }


    // ========================================================
    // GETTERS AND SETTERS — AUDIT INFORMATION
    // ========================================================

    public OffsetDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(OffsetDateTime createdAt) {
        this.createdAt = createdAt;
    }
}
