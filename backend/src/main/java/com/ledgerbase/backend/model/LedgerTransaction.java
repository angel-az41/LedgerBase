package com.ledgerbase.backend.model;

import java.time.LocalDate;
import java.time.OffsetDateTime;
import java.util.Locale;

/**
 * Represents the header of a financial transaction.
 *
 * The core fields map to the PostgreSQL "transactions" table.
 *
 * Journal numbering is stored separately in:
 *
 * - transaction_journal_numbers
 *
 * Each business maintains its own journal numbering sequence.
 *
 * A transaction may contain multiple ledger entries,
 * which are represented by the LedgerEntry model.
 */
public class LedgerTransaction {

    // ============================================================
    // 1. TRANSACTION IDENTIFIERS
    // ============================================================

    /**
     * Globally unique transaction ID generated by PostgreSQL.
     *
     * Used internally for primary keys and foreign keys.
     *
     * Example: 2
     */
    private Long id;

    /**
     * Business that owns this transaction.
     *
     * All transaction queries must remain business-scoped.
     */
    private Long businessId;

    /**
     * Business-specific journal sequence number.
     *
     * Loaded from transaction_journal_numbers.
     *
     * Example:
     * Business 1 -> journal number 1
     * Business 2 -> journal number 1
     *
     * Both can display JE-0001 independently.
     */
    private Long journalNumber;

    /**
     * User who created the transaction.
     */
    private Long createdBy;


    // ============================================================
    // 2. OPTIONAL CLASSIFICATION AND COUNTERPARTIES
    // ============================================================

    private Long categoryId;
    private Long customerId;
    private Long vendorId;


    // ============================================================
    // 3. TRANSACTION DETAILS
    // ============================================================

    // Description of the financial activity.
    private String description;

    // Accounting date, such as 2026-10-01.
    private LocalDate transactionDate;

    // Lifecycle state, such as DRAFT or POSTED.
    private String status;

    // Timestamp when PostgreSQL created the record.
    private OffsetDateTime createdAt;


    // ============================================================
    // 4. IDENTIFIER GETTERS AND SETTERS
    // ============================================================

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Long getBusinessId() {
        return businessId;
    }

    public void setBusinessId(Long businessId) {
        this.businessId = businessId;
    }

    public Long getJournalNumber() {
        return journalNumber;
    }

    public void setJournalNumber(Long journalNumber) {
        this.journalNumber = journalNumber;
    }

    /**
     * Converts a business-specific journal number
     * into a human-readable journal reference.
     *
     * Examples:
     *
     * 1     -> JE-0001
     * 12    -> JE-0012
     * 123   -> JE-0123
     * 10000 -> JE-10000
     *
     * %04d means the number is padded to at least
     * four digits, without limiting larger numbers.
     *
     * If the number has not yet been loaded,
     * return null instead of generating an
     * incorrect journal reference.
     *
     * Jackson will serialize this getter as the
     * "journalReference" field in JSON responses.
     */
    public String getJournalReference() {

        if (journalNumber == null) {
            return null;
        }

        return String.format(
            Locale.ROOT,
            "JE-%04d",
            journalNumber
        );
    }

    public Long getCreatedBy() {
        return createdBy;
    }

    public void setCreatedBy(Long createdBy) {
        this.createdBy = createdBy;
    }


    // ============================================================
    // 5. CLASSIFICATION GETTERS AND SETTERS
    // ============================================================

    public Long getCategoryId() {
        return categoryId;
    }

    public void setCategoryId(Long categoryId) {
        this.categoryId = categoryId;
    }

    public Long getCustomerId() {
        return customerId;
    }

    public void setCustomerId(Long customerId) {
        this.customerId = customerId;
    }

    public Long getVendorId() {
        return vendorId;
    }

    public void setVendorId(Long vendorId) {
        this.vendorId = vendorId;
    }


    // ============================================================
    // 6. TRANSACTION DETAILS GETTERS AND SETTERS
    // ============================================================

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public LocalDate getTransactionDate() {
        return transactionDate;
    }

    public void setTransactionDate(LocalDate transactionDate) {
        this.transactionDate = transactionDate;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public OffsetDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(OffsetDateTime createdAt) {
        this.createdAt = createdAt;
    }
}
