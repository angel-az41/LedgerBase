
-- =====================================================
-- LedgerBase - Database Migration V1
-- Create Core Tables: Users, Businesses, Accounts
-- =====================================================
--
-- This migration establishes the foundation of
-- LedgerBase's relational database.
--
-- Relationships:
-- 1. One user can own multiple businesses.
-- 2. One business can have multiple financial accounts.
--
-- Flyway executes this migration only once per database.
-- =====================================================


-- =====================================================
-- 1. USERS
-- =====================================================
-- Stores application users.
-- Password hashes will be generated by the backend,
-- never stored as plaintext passwords.

CREATE TABLE users (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    email VARCHAR(255) NOT NULL UNIQUE,

    password_hash VARCHAR(255) NOT NULL,

    full_name VARCHAR(150) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_users_email_nonempty
        CHECK (LENGTH(TRIM(email)) > 0)
);


-- =====================================================
-- 2. BUSINESSES
-- =====================================================
-- Each business belongs to a registered user.
-- Each business maintains its own financial records.

CREATE TABLE businesses (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    owner_id BIGINT NOT NULL,

    name VARCHAR(200) NOT NULL,

    currency CHAR(3) NOT NULL DEFAULT 'USD',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_business_owner
        FOREIGN KEY (owner_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_business_name_nonempty
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT chk_business_currency
        CHECK (currency ~ '^[A-Z]{3}$')
);


-- =====================================================
-- 3. ACCOUNTS
-- =====================================================
-- Financial chart of accounts for each business.
--
-- Account types:
-- ASSET     - Cash, bank accounts, receivables
-- LIABILITY - Loans, accounts payable
-- EQUITY    - Owner capital
-- REVENUE   - Sales and service income
-- EXPENSE   - Rent, utilities, salaries
--
-- Account balances will be calculated later using
-- ledger entries rather than stored redundantly.

CREATE TABLE accounts (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    business_id BIGINT NOT NULL,

    code VARCHAR(20) NOT NULL,

    name VARCHAR(150) NOT NULL,

    account_type VARCHAR(20) NOT NULL,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_account_business
        FOREIGN KEY (business_id)
        REFERENCES businesses(id)
        ON DELETE RESTRICT,

    -- Account codes must be unique within a business.
    CONSTRAINT uq_business_account_code
        UNIQUE (business_id, code),

    CONSTRAINT chk_account_type
        CHECK (account_type IN (
            'ASSET',
            'LIABILITY',
            'EQUITY',
            'REVENUE',
            'EXPENSE'
        )),

    CONSTRAINT chk_account_name_nonempty
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT chk_account_code_nonempty
        CHECK (LENGTH(TRIM(code)) > 0)
);


-- =====================================================
-- 4. INDEXES
-- =====================================================
-- Indexes improve lookup performance.
--
-- The primary key and UNIQUE constraints automatically
-- create their own indexes in PostgreSQL.
--
-- This index accelerates lookups of accounts belonging
-- to a particular business.

CREATE INDEX idx_accounts_business_id
ON accounts(business_id);


-- =====================================================
