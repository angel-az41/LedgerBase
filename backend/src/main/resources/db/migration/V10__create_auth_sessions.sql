-- ============================================================
-- LEDGERBASE — PERSISTENT AUTHENTICATION SESSIONS
-- ============================================================

-- Stores server-managed login sessions and refresh token
-- history.
--
-- SECURITY:
--
-- - Access tokens remain short-lived JWTs.
-- - Refresh tokens are random opaque credentials.
-- - Only refresh token hashes are stored in PostgreSQL.
-- - Sessions can expire or be revoked.
-- - Used refresh tokens remain recorded so replay
--   attempts can be detected.
--
-- No existing user, business, accounting, or ledger
-- records are modified by this migration.


-- ============================================================
-- AUTHENTICATED SESSIONS
-- ============================================================

CREATE TABLE auth_sessions (

    -- Random session identifier generated by Java.
    id UUID PRIMARY KEY,

    -- The PostgreSQL user who authenticated.
    user_id BIGINT NOT NULL
        REFERENCES users(id)
        ON DELETE CASCADE,

    -- When the login session was first created.
    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    -- Updated by authenticated session activity.
    --
    -- The backend will enforce the inactivity timeout.
    last_activity_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    -- Absolute deadline for this session.
    --
    -- The backend will initialize this using the
    -- configured maximum session duration.
    absolute_expires_at TIMESTAMPTZ NOT NULL,

    -- NULL means the session has not been revoked.
    --
    -- Logout and detected token replay can revoke it.
    revoked_at TIMESTAMPTZ,

    CONSTRAINT chk_auth_session_expiration
        CHECK (absolute_expires_at > created_at)

);


-- ============================================================
-- USER SESSION LOOKUP
-- ============================================================

CREATE INDEX idx_auth_sessions_user_id
    ON auth_sessions(user_id);


-- ============================================================
-- REFRESH TOKEN HISTORY
-- ============================================================

CREATE TABLE auth_refresh_tokens (

    -- SHA-256 hash of a cryptographically random
    -- refresh token, represented as lowercase hex.
    --
    -- The original token must never be stored here.
    token_hash CHAR(64) PRIMARY KEY,

    -- Session associated with this token.
    session_id UUID NOT NULL
        REFERENCES auth_sessions(id)
        ON DELETE CASCADE,

    -- Token creation timestamp.
    issued_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    -- NULL means the token has not been consumed.
    --
    -- Refreshing a session consumes the old token
    -- before issuing a replacement.
    consumed_at TIMESTAMPTZ,

    CONSTRAINT chk_refresh_token_hash
        CHECK (
            token_hash ~ '^[0-9a-f]{64}$'
        )

);


-- ============================================================
-- SESSION TOKEN LOOKUP
-- ============================================================

CREATE INDEX idx_auth_refresh_tokens_session_id
    ON auth_refresh_tokens(session_id);


-- ============================================================
-- ONE ACTIVE REFRESH TOKEN PER SESSION
-- ============================================================

-- The backend must consume the previous token and
-- create the replacement in one database transaction.
--
-- Row-level locks will coordinate concurrent refresh
-- requests.

CREATE UNIQUE INDEX uq_active_refresh_token_per_session
    ON auth_refresh_tokens(session_id)
    WHERE consumed_at IS NULL;
